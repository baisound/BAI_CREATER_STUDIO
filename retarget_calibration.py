"""Read-only approximate skeleton calibration. Does not synthesize animation or claim correct retargeting."""
import math
from retarget_analysis import compare

def _vec(b,fmt):
    if fmt=='PMX':return b.get('position')
    return b.get('head_local')

def _distance(a,b):
    return math.sqrt(sum((float(x)-float(y))**2 for x,y in zip(a,b)))

def calibrate(source,target):
    report=compare(source,target)
    srole=source.get('suggested_mapping') or {};trole=target.get('suggested_mapping') or {}
    def entries(doc):
        fmt=doc.get('format'); bones=doc.get('metadata',{}).get('bones_detail',[])
        return {b.get('name'): _vec(b,fmt) for b in bones if isinstance(b,dict) and b.get('name') and isinstance(_vec(b,fmt),list) and len(_vec(b,fmt))==3}
    ss,tt=entries(source),entries(target)
    pairs=[]
    for u,v in [('hips','head'),('hips','leftFoot'),('hips','rightFoot'),('leftUpperArm','leftHand'),('rightUpperArm','rightHand')]:
        names=[srole.get(u),srole.get(v),trole.get(u),trole.get(v)]
        if any(not x for x in names) or names[0] not in ss or names[1] not in ss or names[2] not in tt or names[3] not in tt:continue
        ds=_distance(ss[names[0]],ss[names[1]]);dt=_distance(tt[names[2]],tt[names[3]])
        if ds>1e-7 and dt>1e-7 and math.isfinite(ds) and math.isfinite(dt):pairs.append({'segment':u+' → '+v,'source_length':round(ds,6),'target_length':round(dt,6),'ratio':round(dt/ds,6)})
    ratios=sorted(x['ratio'] for x in pairs)
    scale=ratios[len(ratios)//2] if ratios else None
    axes={}
    for role in sorted(set(srole)&set(trole)):
        s=next((x for x in source.get('metadata',{}).get('bones_detail',[]) if x.get('name')==srole[role]),{})
        t=next((x for x in target.get('metadata',{}).get('bones_detail',[]) if x.get('name')==trole[role]),{})
        if s.get('matrix_local') or s.get('local_axis_x') or t.get('local_axis_x') or t.get('fixed_axis'):
            axes[role]={'source_rest_matrix':s.get('matrix_local'), 'target_local_axis_x':t.get('local_axis_x'),'target_local_axis_z':t.get('local_axis_z'),'target_fixed_axis':t.get('fixed_axis')}
    return {'schema':1,'kind':'calibration_proposal','source':source.get('filename'), 'target':target.get('filename'), 'mapping':{srole[k]:trole[k] for k in sorted(set(srole)&set(trole))},'roles':report['common_roles'], 'scale_proposal':scale,'scale_segments':pairs,'axis_metadata':axes,'hip_motion':{'policy':'preserve_local_root_then_apply_confirmed_scale','scale':scale}, 'pose_correction':{'status':'requires_manual_confirmation','quaternion_offsets':{}},'quality':{'mapping_count':report['matched_count'],'scale_segments_count':len(pairs),'verified':False},'warnings':['Scale is a heuristic from skeleton segment lengths, not verified target units.','Bind/rest orientation alignment is not performed. T/A pose difference requires human confirmation.','No output animation, IK, skin correction, or VMD is generated by this endpoint.']}
