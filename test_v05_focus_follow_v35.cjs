const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const env={};env.globalThis=env;
vm.runInNewContext(fs.readFileSync('studio/v05/js/camera-focus-follow-v35.js','utf8'),env);
const api=env.BAIStudioCameraFocusFollowV35;
const snapshot={seconds:1,frame:60,fps:60,focusValid:true,pose:{position:{x:0,y:0,z:0}},lens:{focalLengthMm:50,fStop:2.8,focusDistance:1}};
const target={seconds:1,frame:60,targetId:'head',worldPosition:{x:0,y:3,z:4}};
const ok=api.resolve(snapshot,target);assert.equal(ok.applied,true);assert.equal(ok.state.focusDistance,5);assert.equal(ok.state.lens.fStop,2.8);
assert.equal(api.resolve(snapshot,{...target,seconds:2}).reason,'time_mismatch');
assert.equal(api.resolve(snapshot,{...target,worldPosition:null}).reason,'position_unavailable');
assert.equal(api.resolve(snapshot,{...target,worldPosition:{x:0,y:0,z:0}}).reason,'invalid_distance');
let emits=[],renders=[],logs=[];
const runtime=api.create({emit:x=>emits.push(x),renderFocus:x=>(renders.push(x),{applied:true}),diagnostic:x=>logs.push(x)});
assert.equal(runtime.setTarget(target).reason,'waiting_for_state');
assert.equal(runtime.setSnapshot(snapshot).applied,true);
assert.equal(emits.length,1);assert.equal(renders.length,1);
assert.equal(runtime.setTarget({...target,frame:59}).applied,false);assert.equal(logs[0].reason,'time_mismatch');
assert.equal(runtime.current().focusDistance,5);
assert.ok(fs.readFileSync('studio/v05/index.html','utf8').includes('camera-focus-follow-v35.js'));
console.log('v35 focus-follow assertions passed');
